 await assert.rejects(()=>reverse(db,doc),/INJECTED_REVERSE_FAILURE/);
 assert.deepEqual(await f.fixture.preview(db),old);
 assert.equal((await db.query('select sum(current_weight_kg)::float kg from inventory_batches')).rows[0].kg,228630);
