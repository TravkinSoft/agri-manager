 const after=await f.fixture.preview(db);
 assert.equal(after.potatoPeriodResultKg,825730);
 assert.equal(after.potatoPeriodImpuritiesKg,244000);
 assert.equal(after.impuritiesRemovedKg,244000);
 assert.equal(after.potatoCleanKg,before.potatoCleanKg);
