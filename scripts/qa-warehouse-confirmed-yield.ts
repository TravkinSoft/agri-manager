import assert from "node:assert/strict";
import { buildWarehouseFieldOrigins } from "../lib/warehouse/field-origins";
import { confirmedPlotHectares } from "../lib/dashboard/harvest-plot-hectares";

const t = { id: "one", field_id: "new92", crop_structure_allocation_id: "canonical", net_weight_kg: 200000, op_type: "harvest_incoming", status: "finalized", is_finalized: true, is_voided: false };
const second = { ...t, id: "other-lot", net_weight_kg: 141010 };
const plots = [{ id: "canonical", field_id: "new92", area: 92 }];
const names = new Map([["new92", "виноград"]]);
const mass = new Map([[t.id, 150000], [second.id, 98630]]);
const closed = { id: "shift", closed_at: "2026-09-21T20:00:00Z" };
const segment = { id: "seg", shift_id: closed.id, closed_at: closed.closed_at, hectares_segment: 5.87 };
const hectares = confirmedPlotHectares([segment, segment], [closed], "2026-09-22T07:00:00Z");
const areas = new Map([["canonical", hectares]]);
const result = buildWarehouseFieldOrigins([t], plots, names, [t, second], mass, areas)[0];
assert.equal(result.areaHa, 92);
assert.equal(result.harvestedAreaHa, 5.87);
assert.equal(result.cleanWeightKg, 150000, "local lot mass stays local");
assert.equal(result.yieldCleanWeightKg, 248630, "yield includes all plot receipts, not just this lot");
assert.equal(result.yieldTPerHa, 248.63 / 5.87);
assert.notEqual(result.yieldTPerHa, 248.63 / 92);
assert.equal(result.yieldStatus, "confirmed");
const open = { ...segment, id: "open", shift_id: "today", closed_at: null, hectares_segment: null };
const pending = new Map([["canonical", confirmedPlotHectares([segment, open], [closed, { id: "today", closed_at: null }], "2026-09-22T07:00:00Z")]]);
const waiting = buildWarehouseFieldOrigins([t], plots, names, [t, second], mass, pending)[0];
assert.equal(waiting.yieldStatus, "awaiting_shift");
assert.equal(waiting.yieldTPerHa, null);
assert.equal(waiting.harvestedAreaHa, 5.87);
assert.equal(buildWarehouseFieldOrigins([t], plots, names, [t], mass)[0].yieldTPerHa, null);
const excess = new Map([["canonical", { ...hectares, harvestedAreaHa: 93 }]]);
assert.equal(buildWarehouseFieldOrigins([t], plots, names, [t], mass, excess)[0].yieldStatus, "area_exceeds_plan");
const old = { ...t, id: "old", field_id: "old54", crop_structure_allocation_id: "old" };
const both = buildWarehouseFieldOrigins([t, old], [...plots, { id: "old", field_id: "old54", area: 54 }], new Map([...Array.from(names), ["old54", "виноград"]]), [t, second, old], new Map([...Array.from(mass), ["old", 520000]]), new Map([...Array.from(areas), ["old", { ...hectares, harvestedAreaHa: 52 }]]));
assert.equal(both.length, 2, "same-name old54 and new92 remain separate");
assert.equal(both.find(r => r.fieldId === "old54")?.yieldTPerHa, 10);
assert.equal(buildWarehouseFieldOrigins([t], plots, names, [t], undefined, areas)[0].yieldTPerHa, null, "receipt weight cannot masquerade as clean crop");
console.log("PASS confirmed yield: 92/5.87, all-lot numerator, open shift, missing/invalid area, old54/52 unchanged");
